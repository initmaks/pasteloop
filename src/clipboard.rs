//! Pasteboard capture rules: the skip checks, classification of a snapshot into an item, and
//! representation capping. The poller that drives them lives in `lib.rs`; everything here is
//! plain Rust so the rules are unit-testable.

use std::io::Cursor;

use crate::macos;
use crate::store::{Kind, NewImage, NewItem};

pub const MARKER_CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const MARKER_TRANSIENT: &str = "org.nspasteboard.TransientType";
pub const MARKER_AUTOGENERATED: &str = "org.nspasteboard.AutoGeneratedType";

pub const UTI_FILE_URL: &str = "public.file-url";
pub const UTI_PNG: &str = "public.png";
pub const UTI_TIFF: &str = "public.tiff";
pub const UTI_JPEG: &str = "public.jpeg";
pub const UTI_HEIC: &str = "public.heic";
pub const UTI_UTF8: &str = "public.utf8-plain-text";
pub const UTI_RTF: &str = "public.rtf";
pub const UTI_HTML: &str = "public.html";

/// Largest image item stored as-is; bigger images are downscaled and marked truncated.
pub const MAX_IMAGE_BYTES: usize = 50 * 1024 * 1024;
/// Longest edge of the downscaled copy stored for oversized images.
pub const TRUNCATED_LONG_EDGE: u32 = 2048;
/// RTF and HTML representations larger than this are dropped (plain text is always kept).
pub const MAX_RICH_BYTES: usize = 2 * 1024 * 1024;
/// Hard cap on a capture; anything larger is skipped.
pub const MAX_TOTAL_BYTES: usize = 200 * 1024 * 1024;

/// What the poller read from the general pasteboard, before classification.
#[derive(Clone, Debug, Default)]
pub struct Snapshot {
    pub change_count: i64,
    pub types: Vec<String>,
    pub file_paths: Vec<String>,
    /// The best image representation present: (bytes, UTI).
    pub image: Option<(Vec<u8>, &'static str)>,
    pub text: Option<String>,
    pub rtf: Option<Vec<u8>>,
    pub html: Option<Vec<u8>>,
}

/// Why a pasteboard change produced no item. Logged at debug level, never with content.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Skip {
    OwnWrite,
    Paused,
    Concealed,
    Transient,
    AutoGenerated,
    IgnoredApp(String),
    TooLarge(usize),
    Unclassified(Vec<String>),
    /// The pasteboard changed again while it was being read; the next poll takes the new copy.
    Superseded,
}

/// Privacy switches that gate capture, copied from settings at each poll.
#[derive(Clone, Debug)]
pub struct CaptureRules<'a> {
    pub paused: bool,
    pub skip_concealed: bool,
    pub skip_transient: bool,
    pub ignored_bundle_ids: &'a [String],
    pub own_change_count: Option<i64>,
}

/// Applies the skip rules in the order the spec lists them. They need only the change count, the
/// type list, and the source app, so a skipped copy is never read. The size cap needs the data
/// and is checked in [`build_item`].
pub fn check_skip(
    change_count: i64,
    types: &[String],
    source_bundle_id: Option<&str>,
    rules: &CaptureRules,
) -> Option<Skip> {
    if rules.own_change_count == Some(change_count) {
        return Some(Skip::OwnWrite);
    }
    if rules.paused {
        return Some(Skip::Paused);
    }
    let has = |marker: &str| types.iter().any(|t| t == marker);
    if rules.skip_concealed && has(MARKER_CONCEALED) {
        return Some(Skip::Concealed);
    }
    if rules.skip_transient && (has(MARKER_TRANSIENT) || has(MARKER_AUTOGENERATED)) {
        return Some(if has(MARKER_TRANSIENT) {
            Skip::Transient
        } else {
            Skip::AutoGenerated
        });
    }
    if let Some(bundle) = source_bundle_id
        && rules.ignored_bundle_ids.iter().any(|b| b == bundle)
    {
        return Some(Skip::IgnoredApp(bundle.to_string()));
    }
    None
}

/// Pasteboard types the capture engine treats as images.
pub fn is_image_type(uti: &str) -> bool {
    matches!(uti, UTI_PNG | UTI_TIFF | UTI_JPEG | UTI_HEIC)
        || uti == "public.image"
        || uti.starts_with("public.image.")
        || matches!(
            uti,
            "public.jpeg-2000"
                | "com.compuserve.gif"
                | "org.webmproject.webp"
                | "com.microsoft.bmp"
        )
}

fn has_text_type(types: &[String]) -> bool {
    types
        .iter()
        .any(|t| matches!(t.as_str(), UTI_UTF8 | UTI_RTF | UTI_HTML))
}

/// Whether a copy with these types is an image rather than text. Spreadsheets and rich editors
/// ship a TIFF rendering next to the text, and that copy is text; only a raster type the user
/// could not have typed (PNG, JPEG, HEIC, ...) or a TIFF without text makes an image.
pub fn image_wins(types: &[String]) -> bool {
    let has_raster = types.iter().any(|t| is_image_type(t) && t != UTI_TIFF);
    let has_tiff = types.iter().any(|t| t == UTI_TIFF);
    has_raster || (has_tiff && !has_text_type(types))
}

/// Classification from pasteboard types and the plain text, first match wins.
pub fn classify(types: &[String], plain_text: Option<&str>) -> Option<Kind> {
    if types.iter().any(|t| t == UTI_FILE_URL) {
        return Some(Kind::File);
    }
    if image_wins(types) {
        return Some(Kind::Image);
    }
    if let Some(text) = plain_text {
        if color_from_text(text).is_some() {
            return Some(Kind::Color);
        }
        if single_url(text).is_some() {
            return Some(Kind::Link);
        }
    }
    if has_text_type(types) || plain_text.is_some_and(|t| !t.is_empty()) {
        return Some(Kind::Text);
    }
    None
}

/// The readable text of an HTML fragment, roughly as a browser copies it: tags dropped, source
/// line breaks as spaces, blocks on their own lines and paragraphs apart, scripts and styles left
/// out, entities decoded.
pub fn html_to_text(html: &str) -> String {
    // Ensures `out` ends with at least `n` line breaks (none at the very start).
    fn breaks(out: &mut String, n: usize) {
        if out.trim().is_empty() {
            return;
        }
        let have = out.len() - out.trim_end_matches('\n').len();
        for _ in have..n {
            out.push('\n');
        }
    }
    let mut out = String::with_capacity(html.len() / 2);
    let mut rest = html;
    loop {
        let lt = rest.find('<').unwrap_or(rest.len());
        let text = decode_entities(&rest[..lt]);
        out.extend(
            text.chars()
                .map(|c| if c.is_whitespace() { ' ' } else { c }),
        );
        if lt == rest.len() {
            break;
        }
        let tag_end = rest[lt..].find('>').map_or(rest.len(), |i| lt + i + 1);
        let tag = rest[lt + 1..tag_end]
            .trim_end_matches('>')
            .to_ascii_lowercase();
        let closing = tag.starts_with('/');
        let name: String = tag
            .trim_start_matches('/')
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        rest = &rest[tag_end..];
        match name.as_str() {
            "script" | "style" | "head" | "title" if !closing => {
                let close = format!("</{name}");
                rest = rest
                    .to_ascii_lowercase()
                    .find(&close)
                    .map_or("", |i| &rest[i..]);
            }
            "br" => out.push('\n'),
            "p" | "h1" | "h2" | "h3" | "h4" | "h5" | "h6" | "blockquote" | "pre" | "table" => {
                breaks(&mut out, 2)
            }
            "div" | "li" | "tr" | "ul" | "ol" | "section" | "article" | "header" | "footer"
            | "hr" => breaks(&mut out, 1),
            "td" | "th" => out.push(' '),
            _ => {}
        }
    }
    let mut text = String::with_capacity(out.len());
    let mut blank = false;
    for line in out.lines() {
        let line = line.split_whitespace().collect::<Vec<_>>().join(" ");
        if line.is_empty() {
            blank = !text.is_empty();
            continue;
        }
        if blank {
            text.push('\n');
            blank = false;
        }
        text.push_str(&line);
        text.push('\n');
    }
    text.trim_end().to_string()
}

fn decode_entities(s: &str) -> std::borrow::Cow<'_, str> {
    if !s.contains('&') {
        return std::borrow::Cow::Borrowed(s);
    }
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(amp) = rest.find('&') {
        out.push_str(&rest[..amp]);
        rest = &rest[amp..];
        let decoded = rest.find(';').filter(|&semi| semi <= 10).and_then(|semi| {
            let entity = &rest[1..semi];
            let ch = match entity {
                "amp" => Some('&'),
                "lt" => Some('<'),
                "gt" => Some('>'),
                "quot" => Some('"'),
                "apos" => Some('\''),
                "nbsp" => Some(' '),
                _ => {
                    let code = match entity.strip_prefix("#x").or(entity.strip_prefix("#X")) {
                        Some(hex) => u32::from_str_radix(hex, 16).ok(),
                        None => entity.strip_prefix('#').and_then(|d| d.parse().ok()),
                    };
                    code.and_then(char::from_u32)
                }
            };
            ch.map(|c| (c, semi))
        });
        match decoded {
            Some((c, semi)) => {
                out.push(c);
                rest = &rest[semi + 1..];
            }
            None => {
                out.push('&');
                rest = &rest[1..];
            }
        }
    }
    out.push_str(rest);
    std::borrow::Cow::Owned(out)
}

/// A standalone six-hex-digit token, with an optional leading `#`, is a color only if it has
/// the `#` or contains at least one letter A–F. Returns the normalized `#RRGGBB`.
pub fn color_from_text(text: &str) -> Option<String> {
    let token = text.trim();
    let (hashed, hex) = match token.strip_prefix('#') {
        Some(rest) => (true, rest),
        None => (false, token),
    };
    if hex.len() != 6 || !hex.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }
    let has_letter = hex.bytes().any(|b| b.is_ascii_alphabetic());
    if hashed || has_letter {
        Some(format!("#{}", hex.to_ascii_uppercase()))
    } else {
        None
    }
}

/// The trimmed text is exactly one `http`/`https` URL with a host and no inner whitespace.
pub fn single_url(text: &str) -> Option<String> {
    let token = text.trim();
    if token.is_empty() || token.chars().any(char::is_whitespace) {
        return None;
    }
    let lower = token.to_ascii_lowercase();
    if !(lower.starts_with("http://") || lower.starts_with("https://")) {
        return None;
    }
    let url = url::Url::parse(token).ok()?;
    url.host_str().filter(|h| !h.is_empty())?;
    Some(token.to_string())
}

/// Heuristic for rendering text in a monospaced font: at least 30 % of lines start with
/// whitespace, or the density of `{`, `;`, and `=>` is high.
pub fn looks_like_code(text: &str) -> bool {
    let (mut lines, mut indented) = (0usize, 0usize);
    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        lines += 1;
        if line.starts_with([' ', '\t']) {
            indented += 1;
        }
    }
    if lines == 0 {
        return false;
    }
    if lines >= 2 && indented * 10 >= lines * 3 {
        return true;
    }
    let symbols = text.matches(['{', ';']).count() + text.matches("=>").count();
    symbols >= 2 && symbols * 40 >= text.chars().count()
}

/// Turns a snapshot into the row to store. Image bytes are normalized here (TIFF to PNG,
/// oversized images downscaled). Fails with `Skip::TooLarge` over the capture cap and with
/// `Skip::Unclassified` when no rule matches.
/// File extensions of images a file card can show.
pub const IMAGE_EXTENSIONS: &[&str] = &[
    "png", "jpg", "jpeg", "gif", "heic", "heif", "tif", "tiff", "webp", "bmp",
];

pub fn is_image_path(path: &str) -> bool {
    std::path::Path::new(path)
        .extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| IMAGE_EXTENSIONS.contains(&e.to_ascii_lowercase().as_str()))
}

/// A picture for a file card: the first image file among `paths` while it is on disk, else an
/// image the copy carried along (screenshot tools put the picture next to the file). Kept as a
/// smaller copy, so the card keeps it after the file is moved or deleted.
pub fn file_preview(paths: &[String], carried: Option<Vec<u8>>) -> Option<NewImage> {
    use std::io::Read;
    let from_disk = paths.iter().find(|p| is_image_path(p)).and_then(|p| {
        let mut bytes = Vec::new();
        std::fs::File::open(p)
            .ok()?
            .take(MAX_IMAGE_BYTES as u64 + 1)
            .read_to_end(&mut bytes)
            .ok()?;
        (bytes.len() <= MAX_IMAGE_BYTES).then_some(bytes)
    });
    let bytes = from_disk.or(carried)?;
    let (bytes, mime, width, height) =
        crate::jobs::preview_image(&bytes, crate::jobs::FILE_PREVIEW_LONG_EDGE).ok()?;
    Some(NewImage {
        png_or_original: bytes,
        mime,
        width: width as i64,
        height: height as i64,
        truncated: false,
    })
}

pub fn build_item(
    mut snapshot: Snapshot,
    source: Option<&macos::FrontApp>,
) -> Result<NewItem, Skip> {
    // Some apps (web views, Chromium) copy HTML without a plain-text version.
    if snapshot.text.as_deref().is_none_or(|t| t.trim().is_empty())
        && let Some(html) = &snapshot.html
    {
        let text = html_to_text(&String::from_utf8_lossy(html));
        if !text.is_empty() {
            snapshot.text = Some(text);
        }
    }
    let total = snapshot.image.as_ref().map_or(0, |(b, _)| b.len())
        + snapshot.text.as_ref().map_or(0, String::len)
        + snapshot.rtf.as_ref().map_or(0, Vec::len)
        + snapshot.html.as_ref().map_or(0, Vec::len);
    if total > MAX_TOTAL_BYTES {
        return Err(Skip::TooLarge(total));
    }
    let Some(kind) = classify(&snapshot.types, snapshot.text.as_deref()) else {
        return Err(Skip::Unclassified(snapshot.types));
    };
    let mut item = NewItem {
        kind: Some(kind),
        source_bundle_id: source.and_then(|a| a.bundle_id.clone()),
        source_app_name: source.and_then(|a| a.name.clone()),
        ..Default::default()
    };
    match kind {
        Kind::File => {
            if snapshot.file_paths.is_empty() {
                return Err(Skip::Unclassified(snapshot.types));
            }
            item.image = file_preview(&snapshot.file_paths, snapshot.image.map(|(b, _)| b));
            item.files = snapshot.file_paths;
        }
        Kind::Image => {
            let Some((bytes, uti)) = snapshot.image else {
                return Err(Skip::Unclassified(snapshot.types));
            };
            item.image = Some(normalize_image(bytes, uti)?);
        }
        Kind::Color => item.text = snapshot.text.as_deref().and_then(color_from_text),
        Kind::Link => item.text = snapshot.text.as_deref().and_then(single_url),
        Kind::Text => {
            let fits = |b: &Vec<u8>| b.len() <= MAX_RICH_BYTES;
            item.rich = match (snapshot.rtf, snapshot.html) {
                (Some(rtf), _) if fits(&rtf) => Some((rtf, UTI_RTF)),
                (_, Some(html)) if fits(&html) => Some((html, UTI_HTML)),
                _ => None,
            };
            item.text = Some(snapshot.text.unwrap_or_default());
        }
    }
    Ok(item)
}

/// PNG, JPEG, and HEIC are stored as-is; TIFF is converted to PNG; anything over the cap is
/// downscaled to a 2048 px PNG and marked truncated.
fn normalize_image(bytes: Vec<u8>, uti: &'static str) -> Result<NewImage, Skip> {
    let (bytes, mime) = match uti {
        UTI_PNG => (bytes, "image/png"),
        UTI_JPEG => (bytes, "image/jpeg"),
        UTI_HEIC => (bytes, "image/heic"),
        _ => match macos::image_to_png(&bytes) {
            Some(png) => (png, "image/png"),
            None => return Err(Skip::Unclassified(vec![uti.to_string()])),
        },
    };
    let (width, height) = image_dimensions(&bytes)
        .or_else(|| macos::image_dimensions(&bytes))
        .unwrap_or((0, 0));
    if bytes.len() <= MAX_IMAGE_BYTES {
        return Ok(NewImage {
            png_or_original: bytes,
            mime,
            width: width as i64,
            height: height as i64,
            truncated: false,
        });
    }
    let decoded = image::load_from_memory(&bytes)
        .ok()
        .or_else(|| macos::image_to_png(&bytes).and_then(|png| image::load_from_memory(&png).ok()))
        .ok_or(Skip::TooLarge(bytes.len()))?;
    let small = decoded.thumbnail(TRUNCATED_LONG_EDGE, TRUNCATED_LONG_EDGE);
    let mut out = Vec::new();
    small
        .write_to(&mut Cursor::new(&mut out), image::ImageFormat::Png)
        .map_err(|_| Skip::TooLarge(bytes.len()))?;
    Ok(NewImage {
        width: small.width() as i64,
        height: small.height() as i64,
        png_or_original: out,
        mime: "image/png",
        truncated: true,
    })
}

/// Reads only the header, so it is cheap even for very large images.
pub fn image_dimensions(bytes: &[u8]) -> Option<(u32, u32)> {
    image::ImageReader::new(Cursor::new(bytes))
        .with_guessed_format()
        .ok()?
        .into_dimensions()
        .ok()
}

