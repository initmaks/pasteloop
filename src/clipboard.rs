    #[test]
    fn spreadsheet_tiff_reads_as_text() {
        // The reader fetches text, not the TIFF, when a TIFF comes with text types.
        assert!(!image_wins(&types(&[UTI_TIFF, UTI_UTF8])));
        assert!(!image_wins(&types(&[UTI_TIFF, UTI_RTF])));
        assert!(image_wins(&types(&[UTI_TIFF])));
        assert!(image_wins(&types(&[UTI_PNG, UTI_UTF8])));
        let copy = Snapshot {
            types: types(&[UTI_TIFF, UTI_UTF8]),
            text: Some("A1\tB1".into()),
            ..Default::default()
        };
        let item = build_item(copy, None).unwrap();
        assert_eq!(item.kind, Some(Kind::Text));
        assert_eq!(item.text.as_deref(), Some("A1\tB1"));
    }

    #[test]
    fn skip_rules_in_order() {
        let ignored = ["com.1password.1password".to_string()];
        let base = CaptureRules {
            paused: false,
            skip_concealed: true,
            skip_transient: true,
            ignored_bundle_ids: &ignored,
            own_change_count: Some(7),
        };
        let concealed = types(&[UTI_UTF8, MARKER_CONCEALED]);
        assert_eq!(
            check_skip(7, &concealed, Some("com.1password.1password"), &base),
            Some(Skip::OwnWrite)
        );
        let paused = CaptureRules {
            paused: true,
            ..base.clone()
        };
        assert_eq!(check_skip(8, &concealed, None, &paused), Some(Skip::Paused));
        assert_eq!(
            check_skip(8, &concealed, Some("com.apple.Safari"), &base),
            Some(Skip::Concealed)
        );
        let allow = CaptureRules {
            skip_concealed: false,
            ..base.clone()
        };
        assert_eq!(
            check_skip(8, &concealed, Some("com.apple.Safari"), &allow),
            None
        );
        let transient = types(&[UTI_UTF8, MARKER_TRANSIENT]);
        assert_eq!(
            check_skip(8, &transient, None, &base),
            Some(Skip::Transient)
        );
        let generated = types(&[UTI_UTF8, MARKER_AUTOGENERATED]);
        assert_eq!(
            check_skip(8, &generated, None, &base),
            Some(Skip::AutoGenerated)
        );
        let plain = types(&[UTI_UTF8]);
        assert_eq!(
            check_skip(8, &plain, Some("com.1password.1password"), &base),
            Some(Skip::IgnoredApp("com.1password.1password".into()))
        );
        assert_eq!(check_skip(8, &plain, Some("com.apple.Notes"), &base), None);

        let huge = Snapshot {
            types: plain,
            text: Some("x".repeat(MAX_TOTAL_BYTES + 1)),
            ..Default::default()
        };
        assert!(matches!(build_item(huge, None), Err(Skip::TooLarge(_))));
    }

    #[test]
    fn build_item_representations() {
        let snap = Snapshot {
            change_count: 1,
            types: types(&[UTI_UTF8, UTI_RTF, UTI_HTML]),
            text: Some("Hello".into()),
            rtf: Some(b"{\\rtf1 Hello}".to_vec()),
            html: Some(b"<b>Hello</b>".to_vec()),
            ..Default::default()
        };
        let item = build_item(snap.clone(), None).unwrap();
        assert_eq!(item.kind, Some(Kind::Text));
        assert_eq!(item.text.as_deref(), Some("Hello"));
        assert_eq!(
            item.rich.as_ref().map(|r| r.1),
            Some(UTI_RTF),
            "rtf preferred over html"
        );

        let big_rtf = Snapshot {
            rtf: Some(vec![b'x'; MAX_RICH_BYTES + 1]),
            ..snap.clone()
        };
        let item = build_item(big_rtf, None).unwrap();
        assert_eq!(
            item.rich.as_ref().map(|r| r.1),
            Some(UTI_HTML),
            "oversized rtf falls back"
        );

        let color = Snapshot {
            types: types(&[UTI_UTF8]),
            text: Some(" #abcdef ".into()),
            ..Default::default()
        };
        let item = build_item(color, None).unwrap();
        assert_eq!(item.kind, Some(Kind::Color));
        assert_eq!(item.text.as_deref(), Some("#ABCDEF"));

        let files = Snapshot {
            types: types(&[UTI_FILE_URL]),
            file_paths: vec!["/a".into(), "/b".into()],
            ..Default::default()
        };
        let item = build_item(files, None).unwrap();
        assert_eq!(item.files, vec!["/a", "/b"]);

        let unknown = Snapshot {
            types: types(&["com.example.private"]),
            ..Default::default()
        };
        assert!(matches!(
            build_item(unknown, None),
            Err(Skip::Unclassified(_))
        ));
    }

